const defaultContract = contracts["platform-public-v1"];

export function parseArguments(argv) {
  let contract = defaultContract;
  let outputArgument;
  if (argv.length === 2 && argv[0] === "--schema" && argv[1]) {
    contract = contracts[argv[1]];
  } else if (argv.length === 2 && argv[0] === "--output" && argv[1]) {
    outputArgument = argv[1];
  } else if (
    argv.length === 4 && argv[0] === "--schema" && argv[1] &&
    argv[2] === "--output" && argv[3]
  ) {
    contract = contracts[argv[1]];
    outputArgument = argv[3];
  } else if (argv.length !== 0) {
    throw new Error("public_openapi_generation_arguments_invalid");
  }
  if (contract === undefined) throw new Error("public_openapi_generation_schema_invalid");
  if (outputArgument === undefined) return { contract, outputs: [...contract.defaultOutputs] };
  const requestedOutput = resolve(outputArgument);
  const output = resolve(realpathSync(dirname(requestedOutput)), basename(requestedOutput));
  const relativeToTemporaryRoot = relative(realpathSync(tmpdir()), output);
  if (
    relativeToTemporaryRoot === "" ||
    relativeToTemporaryRoot.startsWith("..") ||
    isAbsolute(relativeToTemporaryRoot)
  ) {
    throw new Error("public_openapi_generation_output_must_be_temporary");
  }
  return { contract, outputs: [output] };
}

async function existingDirectory(path) {
  try {
    const stat = await lstat(path);
    if (!stat.isDirectory() || stat.isSymbolicLink()) {
      throw new Error("public_openapi_generation_target_invalid");
    }
    return true;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

async function publishGeneratedDirectory(staging, output) {
  const exists = await existingDirectory(output);
  const isDefaultOutput = Object.values(contracts).some(({ defaultOutputs }) =>
    defaultOutputs.includes(output),
  );
  if (exists && !isDefaultOutput) {
    throw new Error("public_openapi_generation_refuses_existing_output");
  }
  if (!exists) {
    await rename(staging, output);
    return;
  }

  const backup = `${output}.previous-${process.pid}-${Date.now()}`;
  await rename(output, backup);
  try {
    await rename(staging, output);
  } catch (error) {
    await rename(backup, output);
    throw error;
  }
  await rm(backup, { recursive: true });
}

function metadataSource(contract, { sourceDigestSha256, artifactDigestSha256, generatorVersion }) {
  return `// @generated by Root contract authority; do not edit.\n` +
    `export const ${contract.metadataName} = Object.freeze({\n` +
    `  schemaId: ${JSON.stringify(contract.schemaId)},\n` +
    `  contractVersion: "1",\n` +
    `  sourcePath: ${JSON.stringify(contract.sourceLabel)},\n` +
    `  sourceDigestSha256: "${sourceDigestSha256}",\n` +
    `  artifactDigestSha256: "${artifactDigestSha256}",\n` +
    `  generator: "@hey-api/openapi-ts",\n` +
    `  generatorVersion: "${generatorVersion}",\n` +
    `  artifactKind: "types-zod4-and-operation-registry",\n` +
    `} as const);\n`;
}

async function artifactDigest(output) {
  const hash = createHash("sha256");
  const files = (await readdir(output, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name !== "contract-metadata.ts")
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));
  for (const file of files) {
    hash.update(`${file}\0`);
    hash.update(await readFile(resolve(output, file)));
    hash.update("\0");
  }
  return hash.digest("hex");
}

function operationTypePrefix(operationId) {
  const prefix = operationId
    .replaceAll(/[-_.]+([A-Za-z0-9])/gu, (_, value) => value.toUpperCase());
  return `${prefix[0].toUpperCase()}${prefix.slice(1)}`;
}

function removeRawClientOptions(source) {
  const file = ts.createSourceFile("types.gen.ts", source, ts.ScriptTarget.Latest, true);
  const matches = file.statements.filter(
    (statement) =>
      (ts.isTypeAliasDeclaration(statement) || ts.isInterfaceDeclaration(statement)) &&
      statement.name.text === "ClientOptions",
  );
  if (matches.length !== 1) {
    throw new Error("public_openapi_client_options_shape_changed");
  }
  const declaration = matches[0];
  const members = ts.isTypeAliasDeclaration(declaration) && ts.isTypeLiteralNode(declaration.type)
    ? declaration.type.members
    : ts.isInterfaceDeclaration(declaration)
      ? declaration.members
      : [];
  if (
    members.length !== 1 ||
    !ts.isPropertySignature(members[0]) ||
    !members[0].name ||
    members[0].name.getText(file) !== "baseUrl"
  ) {
    throw new Error("public_openapi_client_options_shape_changed");
  }
  let end = declaration.end;
  while (source[end] === "\r" || source[end] === "\n") end += 1;
  const remaining = source.slice(0, declaration.getFullStart()) + source.slice(end);
  return `// @generated by Root contract authority; do not edit.\n\n${remaining.trimStart()}`;
}

function publicIndexSource(generatedIndexSource, contract) {
  const file = ts.createSourceFile("index.ts", generatedIndexSource, ts.ScriptTarget.Latest, true);
  const names = [];
  for (const statement of file.statements) {
    if (
      !ts.isExportDeclaration(statement) ||
      !statement.exportClause ||
      !ts.isNamedExports(statement.exportClause) ||
      statement.moduleSpecifier?.getText(file) !== "'./types.gen.js'"
    ) {
      continue;
    }
    for (const element of statement.exportClause.elements) {
      if (element.name.text !== "ClientOptions") names.push(element.name.text);
    }
  }
  if (names.length === 0 || generatedIndexSource.includes("export type *")) {
    throw new Error("public_openapi_type_exports_shape_changed");
  }
  const canonicalExport = contract.schemaId === "platform-public-v1"
    ? "export * from './media-canonical.js';\nexport * from './artifact-delivery.js';\n"
    : "";
  return `// @generated by Root contract authority; do not edit.\n\n` +
    `export type {\n  ${names.sort((left, right) => left.localeCompare(right)).join(",\n  ")},\n` +
    `} from './types.gen.js';\n` +
    `export * from './operations.gen.js';\n` +
    `export { ${contract.metadataName} } from './contract-metadata.js';\n` + canonicalExport;
}

function artifactDeliverySource() {
  return `// @generated by Root contract authority; do not edit.
export const ARTIFACT_DELIVERY_MAX_RANGE_BYTES = 8_388_608n;
export const ARTIFACT_DELIVERY_MAX_BYTE_OFFSET = 18_446_744_073_709_551_615n;
export type ArtifactDeliveryByteRange =
  | Readonly<{ start: bigint; endInclusive: bigint }>
  | Readonly<{ suffixLength: bigint }>;
export type ArtifactDeliveryCallOptions = Readonly<{
  signal: AbortSignal;
  deadlineMs: number;
  range?: ArtifactDeliveryByteRange;
}>;
export type ArtifactDeliveryCall = Readonly<{
  signal: AbortSignal;
  headers: Readonly<{ "X-Kokoro-Request-Deadline-Ms": string; Range?: string }>;
}>;
export class ArtifactDeliveryError extends Error {
  readonly code: string;
  constructor(code: string) { super(code); this.name = "ArtifactDeliveryError"; this.code = code; }
}
function reject(code: string): never { throw new ArtifactDeliveryError(code); }
function isPlainOwnObject(value: unknown): value is Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}
function closedDataSnapshot(
  value: unknown,
  required: readonly string[],
  optional: readonly string[],
  requiredCode: string,
  shapeCode: string,
): Readonly<Record<string, unknown>> {
  if (!isPlainOwnObject(value)) reject(requiredCode);
  const descriptors = Object.getOwnPropertyDescriptors(value);
  const descriptorKeys = Reflect.ownKeys(descriptors);
  if (descriptorKeys.some((key) => typeof key !== "string")) reject(shapeCode);
  const keys = (descriptorKeys as string[]).sort();
  const allowed = [...required, ...optional].sort();
  if (required.some((key) => !keys.includes(key)) || keys.some((key) => !allowed.includes(key))) reject(shapeCode);
  const snapshot = Object.create(null) as Record<string, unknown>;
  for (const key of keys) {
    const descriptor = descriptors[key];
    if (descriptor === undefined || !("value" in descriptor)) reject("ARTIFACT_DELIVERY_DATA_PROPERTY_REQUIRED");
    Object.defineProperty(snapshot, key, { value: descriptor.value, enumerable: true });
  }
  return Object.freeze(snapshot);
}
function artifactRangeHeader(input: unknown): string {
  const range = closedDataSnapshot(input, [], ["start", "endInclusive", "suffixLength"], "ARTIFACT_DELIVERY_RANGE_INVALID", "ARTIFACT_DELIVERY_RANGE_INVALID");
  const keys = Object.keys(range).sort();
  let header: string;
  if (keys.length === 1 && keys[0] === "suffixLength") {
    if (typeof range.suffixLength !== "bigint" || range.suffixLength < 1n || range.suffixLength > ARTIFACT_DELIVERY_MAX_RANGE_BYTES) reject("ARTIFACT_DELIVERY_RANGE_INVALID");
    header = \`bytes=-\${range.suffixLength}\`;
  } else if (keys.length === 2 && keys[0] === "endInclusive" && keys[1] === "start") {
    const start = range.start;
    const endInclusive = range.endInclusive;
    if (typeof start !== "bigint" || typeof endInclusive !== "bigint" || start < 0n || endInclusive < start || start > ARTIFACT_DELIVERY_MAX_BYTE_OFFSET || endInclusive > ARTIFACT_DELIVERY_MAX_BYTE_OFFSET || endInclusive - start + 1n > ARTIFACT_DELIVERY_MAX_RANGE_BYTES) reject("ARTIFACT_DELIVERY_RANGE_INVALID");
    header = \`bytes=\${start}-\${endInclusive}\`;
  } else {
    reject("ARTIFACT_DELIVERY_RANGE_INVALID");
  }
  if (header.length > 64) reject("ARTIFACT_DELIVERY_RANGE_INVALID");
  return header;
}
export function artifactDeliveryCall(input: ArtifactDeliveryCallOptions): ArtifactDeliveryCall {
  const options = closedDataSnapshot(input, ["signal", "deadlineMs"], ["range"], "ARTIFACT_DELIVERY_OPTIONS_REQUIRED", "ARTIFACT_DELIVERY_OPTIONS_SHAPE_INVALID");
  const signal = options.signal;
  if (!(signal instanceof AbortSignal) || signal.aborted) reject("ARTIFACT_DELIVERY_ABORT_SIGNAL_REQUIRED");
  if (!Number.isInteger(options.deadlineMs) || (options.deadlineMs as number) < 1 || (options.deadlineMs as number) > 30_000) reject("ARTIFACT_DELIVERY_DEADLINE_INVALID");
  const headers: { "X-Kokoro-Request-Deadline-Ms": string; Range?: string } = {
    "X-Kokoro-Request-Deadline-Ms": String(options.deadlineMs),
  };
  if (options.range !== undefined) {
    headers.Range = artifactRangeHeader(options.range);
  }
  return Object.freeze({ signal, headers: Object.freeze(headers) });
}
`;
}

function makeZodObjectsStrict(source) {
  const file = ts.createSourceFile("zod.gen.ts", source, ts.ScriptTarget.Latest, true);
  const replacements = [];
  function visit(node) {
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      node.expression.expression.getText(file) === "z" &&
      node.expression.name.text === "object"
    ) {
      replacements.push({ start: node.expression.name.getStart(file), end: node.expression.name.end });
    }
    ts.forEachChild(node, visit);
  }
  visit(file);
  if (replacements.length === 0) {
    throw new Error("public_openapi_zod_object_shape_changed");
  }
  let result = source;
  for (const replacement of replacements.sort((left, right) => right.start - left.start)) {
    result = result.slice(0, replacement.start) + "strictObject" + result.slice(replacement.end);
  }
  return result;
}

export function hardenPublicZodSchemas(source) {
  const file = ts.createSourceFile("zod.gen.ts", source, ts.ScriptTarget.Latest, true);
  const targets = new Map([
    [
      "zPositiveUint64String",
      '.refine((value) => value.length < 20 || value <= "18446744073709551615", "must fit a positive uint64")',
    ],
  ]);
  const replacements = [];
  for (const statement of file.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || declaration.initializer === undefined) continue;
      const suffix = targets.get(declaration.name.text);
      if (suffix === undefined) continue;
      replacements.push({
        name: declaration.name.text,
        start: declaration.initializer.getStart(file),
        end: declaration.initializer.end,
        text: `(${declaration.initializer.getText(file)})${suffix}`,
      });
    }
  }
  const found = new Set(replacements.map(({ name }) => name));
  for (const name of targets.keys()) {
    if (!found.has(name)) throw new Error(`public_openapi_domain_schema_missing:${name}`);
  }
  let result = source;
  for (const replacement of replacements.sort((left, right) => right.start - left.start)) {
    result = result.slice(0, replacement.start) + replacement.text + result.slice(replacement.end);
  }
  return result;
}

function operationMapSource(document, generatedTypesSource, generatedZodSource, contract) {
  const operations = [...openApiOperations(document).entries()].sort(([left], [right]) =>
    left.localeCompare(right),
  );
  const imports = [];
  const zodImports = [];
  const dataRows = [];
  const responseRows = [];
  const errorRows = [];
  const definitions = [];

  for (const [operationId, { method, path, operation }] of operations) {
    const prefix = operationTypePrefix(operationId);
    for (const suffix of ["Data", "Response", "Error"]) {
      const typeName = `${prefix}${suffix}`;
      if (!generatedTypesSource.includes(`export type ${typeName} =`)) {
        throw new Error(`public_openapi_generated_type_missing:${typeName}`);
      }
      imports.push(typeName);
    }
    const responseSchema = `z${prefix}Response`;
    if (!generatedZodSource.includes(`export const ${responseSchema} =`)) {
      throw new Error(`public_openapi_generated_schema_missing:${responseSchema}`);
    }
    zodImports.push(responseSchema);
    const requestSchemas = {};
    for (const part of ["Body", "Headers", "Path", "Query"]) {
      const schemaName = `z${prefix}${part}`;
      if (generatedZodSource.includes(`export const ${schemaName} =`)) {
        zodImports.push(schemaName);
        requestSchemas[part.toLowerCase()] = schemaName;
      }
    }
    const successStatuses = Object.keys(operation.responses ?? {})
      .filter((status) => /^2[0-9]{2}$/u.test(status))
      .map((status) => Number.parseInt(status, 10))
      .sort((left, right) => left - right);
    if (successStatuses.length === 0) {
      throw new Error(`public_openapi_success_status_missing:${operationId}`);
    }
    dataRows.push(`  readonly ${JSON.stringify(operationId)}: ${prefix}Data;`);
    responseRows.push(`  readonly ${JSON.stringify(operationId)}: ${prefix}Response;`);
    errorRows.push(`  readonly ${JSON.stringify(operationId)}: ${prefix}Error;`);

    const effectiveSecurity = operation.security ?? document.security ?? [];
    const alternatives = effectiveSecurity.map((requirement) =>
      Object.keys(requirement).sort((left, right) => left.localeCompare(right)),
    );
    const recoveryCount = alternatives.filter((alternative) =>
      alternative.includes("ReceiptRecoveryCapability"),
    ).length;
    const receiptRecovery = recoveryCount === 0
      ? "none"
      : recoveryCount === alternatives.length
        ? "required"
        : "alternative";
    definitions.push(
      `  ${JSON.stringify(operationId)}: Object.freeze({\n` +
      `    method: ${JSON.stringify(method.toUpperCase())},\n` +
      `    path: ${JSON.stringify(path)},\n` +
      `    mutation: ${!(["get", "head", "options"].includes(method))},\n` +
      `    receiptRecovery: ${JSON.stringify(receiptRecovery)},\n` +
      `    securityAlternatives: Object.freeze(${JSON.stringify(alternatives)}),\n` +
      `    successStatuses: Object.freeze(${JSON.stringify(successStatuses)}),\n` +
      `    requestSchemas: Object.freeze({\n` +
      `      body: ${requestSchemas.body ?? "null"},\n` +
      `      headers: ${requestSchemas.headers ?? "null"},\n` +
      `      path: ${requestSchemas.path ?? "null"},\n` +
      `      query: ${requestSchemas.query ?? "null"},\n` +
      `    }),\n` +
      `    responseSchema: ${responseSchema},\n` +
      `  }),`,
    );
  }

  return `// @generated by Root contract authority; do not edit.\n` +
    `import type {\n  ${[...new Set(imports)].sort().join(",\n  ")},\n} from './types.gen.js';\n\n` +
    `import {\n  ${[...new Set(zodImports)].sort().join(",\n  ")},\n} from './zod.gen.js';\n\n` +
    `export interface ${contract.operationPrefix}OperationDataMap {\n${dataRows.join("\n")}\n}\n\n` +
    `export interface ${contract.operationPrefix}OperationResponseMap {\n${responseRows.join("\n")}\n}\n\n` +
    `export interface ${contract.operationPrefix}OperationErrorMap {\n${errorRows.join("\n")}\n}\n\n` +
    `export const ${contract.operationsName} = Object.freeze({\n${definitions.join("\n")}\n} as const);\n\n` +
    `export type ${contract.operationPrefix}OperationId = keyof typeof ${contract.operationsName};\n`;
}

export async function generatePublicOpenApi({ output, contract = defaultContract }) {
  const [source, packageJsonSource] = await Promise.all([
    readFile(contract.sourcePath, "utf8"),
    readFile(resolve(contractRoot, "node_modules/@hey-api/openapi-ts/package.json"), "utf8"),
  ]);
  const packageJson = JSON.parse(packageJsonSource);
  if (packageJson.version !== "0.99.0") {
    throw new Error("public_openapi_generator_version_mismatch");
  }

  const document = readOpenApiDocument(source);
  // Site code resolves a registered server-side binding through its transport.
  // Do not generate Hey API's raw baseUrl surface from the contract's
  // documentation-only server entry.
  const generatorDocument = structuredClone(document);
  delete generatorDocument.servers;

  await mkdir(dirname(output), { recursive: true });
  const staging = await mkdtemp(resolve(dirname(output), `.${basename(output)}.staging-`));
  let published = false;
  try {
    await createClient({
      input: generatorDocument,
      output: {
        path: staging,
        importFileExtension: ".js",
      },
      plugins: [
        "@hey-api/typescript",
        { name: "zod", compatibilityVersion: 4 },
      ],
    });

    const indexPath = resolve(staging, "index.ts");
    const typesPath = resolve(staging, "types.gen.ts");
    const zodPath = resolve(staging, "zod.gen.ts");
    const [indexSource, generatedTypesSource, generatedZodSource] = await Promise.all([
      readFile(indexPath, "utf8"),
      readFile(typesPath, "utf8"),
      readFile(zodPath, "utf8"),
    ]);
    const publicTypesSource = removeRawClientOptions(generatedTypesSource);
    const publicZodSource = hardenPublicZodSchemas(makeZodObjectsStrict(generatedZodSource));
    const generatedWrites = [
      writeFile(
        resolve(staging, "operations.gen.ts"),
        operationMapSource(document, generatedTypesSource, publicZodSource, contract),
        "utf8",
      ),
      writeFile(typesPath, publicTypesSource, "utf8"),
      writeFile(zodPath, publicZodSource, "utf8"),
      writeFile(indexPath, publicIndexSource(indexSource, contract), "utf8"),
    ];
    if (contract.schemaId === "platform-public-v1") {
      generatedWrites.push(
        writeFile(resolve(staging, "media-canonical.ts"), MEDIA_CANONICAL_TYPESCRIPT_SOURCE, "utf8"),
        writeFile(resolve(staging, "artifact-delivery.ts"), artifactDeliverySource(), "utf8"),
      );
    }
    await Promise.all(generatedWrites);
    await writeFile(
      resolve(staging, "contract-metadata.ts"),
      metadataSource(contract, {
        sourceDigestSha256: createHash("sha256").update(source).digest("hex"),
        artifactDigestSha256: await artifactDigest(staging),
        generatorVersion: packageJson.version,
      }),
      "utf8",
    );
    await publishGeneratedDirectory(staging, output);
    published = true;
  } finally {
    if (!published) await rm(staging, { recursive: true, force: true });
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  try {
    const { contract, outputs } = parseArguments(process.argv.slice(2));
    for (const output of outputs) await generatePublicOpenApi({ output, contract });
  } catch (error) {
    const reason = error instanceof Error ? error.message : "unknown";
    process.stderr.write(`public_openapi_generation_failed:${reason}\n`);
    process.exitCode = 1;
  }
}
